"""Validate the nine native languages and generate the embedded AS3 catalog.

Run from any directory. --check fails if generated source is out of date.
No external translation service or runtime file loading is used.
"""
from pathlib import Path
import argparse,json,re
ROOT=Path(__file__).resolve().parents[1]
LANGUAGES=('zh','tw','en','ru','ua','pl','de','es','jp')

def generate(check=False):
    data=json.loads((ROOT/'locales/messages.json').read_text('utf8'))
    for key,row in data.items():
        assert set(row)==set(LANGUAGES),(key,'language coverage')
        placeholders=sorted(re.findall(r'\{\d+\}',key))
        for code,value in row.items():
            assert value and '\ufffd' not in value,(key,code,'empty or corrupt')
            assert sorted(re.findall(r'\{\d+\}',value))==placeholders,(key,code,'placeholders')
            assert value.count('\n')==row['en'].count('\n'),(key,code,'line breaks')
    # All literal callers are developer-owned; user names/chat never enter translation.
    literal=r'"(?:[^"\\]|\\.)*"'
    for p in (ROOT/'src').rglob('*.as'):
        if p.name=='RCLocaleMessages.as':continue
        text=p.read_text('utf8')
        for m in re.finditer(r'RCLocale\.(?:text|format)\(('+literal+r')',text):
            key=json.loads(m[1]);assert key in data or key=='SATS',(p,key)
    target=ROOT/'src/modlocales/connect/RCLocaleMessages.as'
    content='// Generated by tools/generate_locales.py; edit locales/messages.json.\n'
    content+='package modlocales.connect {\n   public class RCLocaleMessages {\n      public static const DATA:Object = '
    content+=json.dumps(data,ensure_ascii=False,indent=2)+';\n   }\n}\n'
    if check:assert target.read_text('utf8')==content,'Run tools/generate_locales.py'
    else:target.write_text(content,encoding='utf8')
    return dict(messages=len(data),languages=list(LANGUAGES),translations=len(data)*len(LANGUAGES))

if __name__=='__main__':
    parser=argparse.ArgumentParser();parser.add_argument('--check',action='store_true');args=parser.parse_args()
    print(json.dumps(generate(args.check)))
