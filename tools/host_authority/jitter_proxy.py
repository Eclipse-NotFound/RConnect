"""Ordered loopback-only delay fixture for the real two-process B protocol.

The relay neither decodes nor edits packets. Both directions use the exact
length-prefixed bytes generated by AIR, with a recorded deterministic delay
schedule. It is never started by the player launcher or the mod itself.
"""
import collections
import select
import socket
import struct
import threading
import time


class JitterProxy:
    LIMIT = 1024 * 1024

    def __init__(self, host_port, delays):
        if not delays or any(type(n) is not int or n < 0 or n > 450 for n in delays):
            raise ValueError('Jitter delay schedule must contain integer milliseconds in 0..450')
        self.host_port, self.delays = host_port, list(delays)
        self.server = socket.socket()
        self.server.bind(('127.0.0.1', 0))
        self.port = self.server.getsockname()[1]
        self.server.listen(1)
        self.server.settimeout(.25)
        self.stop_event = threading.Event()
        self.sockets = []
        self.error = None
        self.stats = {name: dict(received=0, sent=0, bytes=0, peak_queue=0,
                                delay_ms_sum=0, delay_ms_max=0, pending=0)
                      for name in ('join_to_host', 'host_to_join')}
        self.thread = threading.Thread(target=self._run, name='B-local-jitter', daemon=True)

    def start(self):
        self.thread.start()

    def _run(self):
        try:
            while not self.stop_event.is_set():
                try:
                    client, peer = self.server.accept()
                    break
                except socket.timeout:
                    continue
            else:
                return
            if peer[0] != '127.0.0.1':
                raise ValueError('Non-loopback peer')
            self.sockets = [client]
            upstream = socket.create_connection(('127.0.0.1', self.host_port), timeout=5)
            self.sockets.append(upstream)
            for stream in self.sockets:
                stream.settimeout(.5)
            directions = [dict(name='join_to_host', source=client, target=upstream),
                          dict(name='host_to_join', source=upstream, target=client)]
            for d in directions:
                d.update(buffer=bytearray(), queue=collections.deque(), index=0, previous=0)
            while not self.stop_event.is_set():
                readable, _, _ = select.select(self.sockets, [], [], .002)
                for d in directions:
                    stat = self.stats[d['name']]
                    if d['source'] in readable:
                        chunk = d['source'].recv(65536)
                        if not chunk:
                            return
                        d['buffer'].extend(chunk)
                        while len(d['buffer']) >= 4:
                            length = struct.unpack_from('>I', d['buffer'])[0]
                            if not 0 < length <= self.LIMIT:
                                raise ValueError('Invalid B frame size at local relay')
                            if len(d['buffer']) < length + 4:
                                break
                            packet = bytes(d['buffer'][:length + 4])
                            del d['buffer'][:length + 4]
                            now = time.monotonic()
                            due = max(d['previous'], now + self.delays[d['index'] % len(self.delays)] / 1000)
                            d['previous'] = due
                            d['index'] += 1
                            d['queue'].append((due, now, packet))
                            stat['received'] += 1
                        stat['peak_queue'] = max(stat['peak_queue'], len(d['queue']))
                        if len(d['buffer']) > 2 * self.LIMIT or len(d['queue']) > 512:
                            raise RuntimeError('Local jitter queue exceeded its test bound')
                    while d['queue'] and d['queue'][0][0] <= time.monotonic():
                        _, arrived, packet = d['queue'].popleft()
                        d['target'].sendall(packet)
                        delay = (time.monotonic() - arrived) * 1000
                        stat['sent'] += 1
                        stat['bytes'] += len(packet)
                        stat['delay_ms_sum'] += delay
                        stat['delay_ms_max'] = max(stat['delay_ms_max'], delay)
                    stat['pending'] = len(d['queue'])
        except (OSError, ValueError, RuntimeError) as error:
            if not self.stop_event.is_set():
                self.error = str(error)
        finally:
            for stream in self.sockets:
                stream.close()

    def stop(self):
        self.stop_event.set()
        self.server.close()
        self.thread.join(timeout=6)
        if self.thread.is_alive():
            raise RuntimeError('Owned local relay failed to exit')
        return dict(schedule_ms=self.delays, error=self.error,
                    directions=self.stats, owned_thread_exited=True)
